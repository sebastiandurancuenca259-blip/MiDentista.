-- 3. FUNCION: es_admin()
--    Verifica si el usuario autenticado tiene su email en la tabla administradores.
--    SECURITY DEFINER -> se ejecuta con los permisos del dueno de la funcion,
--    por lo que puede leer administradores aunque RLS este cerrado.

create or replace function public.es_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.administradores
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

revoke all    on function public.es_admin() from public;
grant execute on function public.es_admin() to anon, authenticated;

comment on function public.es_admin() is
  'Devuelve TRUE si el JWT del usuario tiene un email registrado en administradores.';


-- 4. FUNCION RPC: horarios_ocupados(p_fecha date)
--    Parametro de entrada : p_fecha  (date, formato YYYY-MM-DD)
--    Salida               : tabla con una columna llamada "hora" (text, HH:MM)
--
--    Solo devuelve horas ocupadas; nunca expone datos personales del paciente.
--    Puede ser llamada por usuarios anonimos.

create or replace function public.horarios_ocupados(p_fecha date)
returns table (hora text)
language sql
stable
security definer
set search_path = public
as $$
  select left(hora_cita::text, 5)   -- recorta "HH:MM:SS" a "HH:MM"
  from   public.citas
  where  fecha_cita = p_fecha
    and  estado     <> 'cancelada'
  order  by 1;
$$;

revoke all    on function public.horarios_ocupados(date) from public;
grant execute on function public.horarios_ocupados(date) to anon, authenticated;

comment on function public.horarios_ocupados(date) is
  'Devuelve las horas (HH:MM) ya ocupadas en una fecha, sin exponer datos personales.';


-- 5. FUNCION TRIGGER: validar_nueva_cita()
--    Se ejecuta BEFORE INSERT en citas. Aplica reglas de negocio:
--      - La fecha no puede ser pasada.
--      - Maximo 60 dias de anticipacion.
--      - No se admiten domingos.
--      - Un mismo telefono no puede tener mas de 3 citas activas.
--    Ademas fuerza estado = 'pendiente' y creado_en = now() en toda insercion.

create or replace function public.validar_nueva_cita()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  hoy        date    := (now() at time zone 'America/La_Paz')::date;
  pendientes integer;
begin
  if new.fecha_cita < hoy then
    raise exception 'La fecha de la cita no puede estar en el pasado.'
      using errcode = 'P0001';
  end if;

  if new.fecha_cita > hoy + 60 then
    raise exception 'Solo se pueden reservar citas con hasta 60 dias de anticipacion.'
      using errcode = 'P0001';
  end if;

  if extract(isodow from new.fecha_cita) = 7 then
    raise exception 'La clinica no atiende los domingos.'
      using errcode = 'P0001';
  end if;

  select count(*) into pendientes
  from   public.citas
  where  paciente_telefono = new.paciente_telefono
    and  fecha_cita        >= hoy
    and  estado            in ('pendiente', 'confirmada');

  if pendientes >= 3 then
    raise exception 'Este telefono ya tiene 3 citas por atender. Comunicate con la clinica por WhatsApp.'
      using errcode = 'P0001';
  end if;

  -- Toda cita nueva entra siempre como pendiente.
  new.estado    := 'pendiente';
  new.creado_en := now();
  return new;
end;
$$;

drop trigger if exists citas_validar_insert on public.citas;
create trigger citas_validar_insert
  before insert on public.citas
  for each row execute function public.validar_nueva_cita();


-- 6. ROW LEVEL SECURITY (RLS) — tabla citas
--
--    Permisos PostgREST:
--      - anon / authenticated -> puede insertar (trigger normaliza el estado)
--      - authenticated        -> puede SELECT, UPDATE, DELETE (RLS filtra a admins)
--
--    Politicas:
--      - publico_crea_citas    -> cualquiera puede insertar si estado = 'pendiente'
--      - admin_lee_citas       -> solo admins pueden hacer SELECT
--      - admin_actualiza_citas -> solo admins pueden hacer UPDATE
--      - admin_elimina_citas   -> solo admins pueden hacer DELETE

alter table public.citas enable row level security;

grant usage  on schema public to anon, authenticated;
grant insert on public.citas  to anon, authenticated;
grant select, update, delete  on public.citas to authenticated;

-- Eliminar politicas anteriores para reconstruirlas limpiamente.
do $$
declare
  pol record;
begin
  for pol in
    select policyname
    from   pg_policies
    where  schemaname = 'public' and tablename = 'citas'
  loop
    execute format('drop policy %I on public.citas', pol.policyname);
  end loop;
end;
$$;

create policy "publico_crea_citas" on public.citas
  for insert to anon, authenticated
  with check (estado = 'pendiente');

create policy "admin_lee_citas" on public.citas
  for select to authenticated
  using (public.es_admin());

create policy "admin_actualiza_citas" on public.citas
  for update to authenticated
  using      (public.es_admin())
  with check (public.es_admin());

create policy "admin_elimina_citas" on public.citas
  for delete to authenticated
  using (public.es_admin());


