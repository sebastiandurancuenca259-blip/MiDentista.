-- 1. TABLA: citas
--    Columnas segun el ERD:
--      id, creado_en, servicio_id, dentista_id, fecha_cita, hora_cita,
--      paciente_nombre, paciente_telefono, paciente_email, estado, notas

create table if not exists public.citas (
  id                bigint      generated by default as identity primary key,
  creado_en         timestamptz not null default now(),
  servicio_id       text        not null default 'consulta-general',
  dentista_id       text,
  fecha_cita        date        not null,
  hora_cita         time        not null,
  paciente_nombre   text        not null,
  paciente_telefono text        not null,
  paciente_email    text,
  estado            text        not null default 'pendiente',
  notas             text
);

-- Columnas por si la tabla viene de una version anterior del proyecto.
alter table public.citas add column if not exists dentista_id text;
alter table public.citas add column if not exists estado      text not null default 'pendiente';
alter table public.citas add column if not exists notas       text;

comment on table  public.citas                   is 'Solicitudes de cita enviadas desde el sitio web.';
comment on column public.citas.id                is 'Clave primaria autoincremental.';
comment on column public.citas.creado_en         is 'Fecha y hora UTC en que se registro la cita.';
comment on column public.citas.servicio_id       is 'Identificador del servicio (ej. consulta-general).';
comment on column public.citas.dentista_id       is 'Identificador del dentista asignado (opcional).';
comment on column public.citas.fecha_cita        is 'Fecha de la cita en formato YYYY-MM-DD.';
comment on column public.citas.hora_cita         is 'Hora de inicio de la cita (HH:MM:SS).';
comment on column public.citas.paciente_nombre   is 'Nombre completo del paciente.';
comment on column public.citas.paciente_telefono is 'Numero de celular/telefono del paciente.';
comment on column public.citas.paciente_email    is 'Correo electronico del paciente (opcional).';
comment on column public.citas.estado            is 'pendiente | confirmada | atendida | cancelada';
comment on column public.citas.notas             is 'Notas internas del administrador sobre la cita.';

-- Restriccion: solo estados validos (aplica a filas nuevas).
alter table public.citas drop constraint if exists citas_estado_valido;
alter table public.citas add constraint citas_estado_valido
  check (estado in ('pendiente', 'confirmada', 'atendida', 'cancelada')) not valid;

-- Restriccion: validacion de formato de datos clave.
alter table public.citas drop constraint if exists citas_datos_validos;
alter table public.citas add constraint citas_datos_validos check (
  char_length(paciente_nombre)   between 3 and 100
  and paciente_telefono          ~ '^\+?[0-9]{7,15}$'
  and (paciente_email is null    or char_length(paciente_email) <= 120)
  and char_length(servicio_id)   <= 60
  and (notas is null             or char_length(notas) <= 500)
) not valid;

-- Indice unico: un mismo slot no puede tener dos citas activas.
create unique index if not exists citas_horario_unico
  on public.citas (fecha_cita, hora_cita)
  where estado <> 'cancelada';

-- Indice de rendimiento para filtrar por fecha.
create index if not exists citas_fecha_idx on public.citas (fecha_cita);


